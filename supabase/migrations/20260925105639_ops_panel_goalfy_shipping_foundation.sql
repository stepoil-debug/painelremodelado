
create table if not exists ops_panel.goalfy_sync_runs (
  id uuid primary key default gen_random_uuid(),
  board_id text not null,
  mode text not null default 'cards_api',
  status text not null default 'running' check (status in ('running','success','partial','error')),
  total_cards integer,
  processed_cards integer not null default 0,
  started_at timestamptz not null default now(),
  finished_at timestamptz,
  error text,
  metadata jsonb not null default '{}'::jsonb
);

create table if not exists ops_panel.goalfy_sync_state (
  board_id text primary key,
  mode text not null default 'cards_api',
  status text not null default 'never',
  total_cards integer,
  processed_cards integer not null default 0,
  last_sync_started_at timestamptz,
  last_synced_at timestamptz,
  last_success_at timestamptz,
  last_error text,
  metadata jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists ops_panel.goalfy_phases (
  phase_id text primary key,
  board_id text not null,
  phase_name text not null,
  phase_index numeric,
  archived boolean not null default false,
  raw jsonb not null default '{}'::jsonb,
  synced_at timestamptz not null default now()
);

create table if not exists ops_panel.goalfy_dns (
  card_id text primary key,
  board_id text not null,
  project_core text,
  project_display text,
  dn_number text,
  card_title text,
  phase_id text,
  phase_name text,
  phase_index numeric,
  client text,
  project_manager text,
  destination text,
  dn_for text,
  po_number text,
  items_text text,
  brasfels_items jsonb not null default '[]'::jsonb,
  tags text[] not null default '{}'::text[],
  invoice_number text,
  invoice_url text,
  created_at_source timestamptz,
  updated_at_source timestamptz,
  date_in_current_phase timestamptz,
  finished_at_source timestamptz,
  ready_at timestamptz,
  shipped_at timestamptz,
  is_ready boolean not null default false,
  is_shipped boolean not null default false,
  is_active boolean not null default true,
  material_scope text not null default 'unknown'
    check (material_scope in ('spool','loose','mixed','other','unknown')),
  sync_run_id uuid references ops_panel.goalfy_sync_runs(id) on delete set null,
  raw jsonb not null default '{}'::jsonb,
  synced_at timestamptz not null default now()
);

create table if not exists ops_panel.goalfy_dn_items (
  id bigint generated by default as identity primary key,
  card_id text not null references ops_panel.goalfy_dns(card_id) on delete cascade,
  project_core text,
  item_key text not null,
  item_label text,
  relation_id text,
  item_type text,
  quantity numeric,
  source_field text not null default 'unknown',
  raw jsonb not null default '{}'::jsonb,
  synced_at timestamptz not null default now(),
  unique(card_id,item_key,source_field)
);

create table if not exists ops_panel.goalfy_dn_phase_history (
  id bigint generated by default as identity primary key,
  card_id text not null references ops_panel.goalfy_dns(card_id) on delete cascade,
  phase_id text,
  phase_name text not null,
  phase_order numeric,
  entered_at timestamptz,
  exited_at timestamptz,
  duration_minutes numeric,
  raw jsonb not null default '{}'::jsonb,
  synced_at timestamptz not null default now()
);

create index if not exists goalfy_dns_project_idx on ops_panel.goalfy_dns(project_core) where is_active;
